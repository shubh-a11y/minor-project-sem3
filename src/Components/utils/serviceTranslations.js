// Helper function to get translated service content
export const getTranslatedService = ( service, language ) =>
{
    if ( !service ) return service;

    const translation = serviceTranslations[ service.id ];

    if ( !translation )
    {
        // No translation available, return original service
        return service;
    }

    const translatedSteps = service.steps.map( ( step, index ) =>
    {
        const stepTranslation = translation.steps?.[ index ];
        if ( !stepTranslation )
        {
            return step;
        }

        return {
            ...step,
            text: stepTranslation.text?.[ language ] || stepTranslation.text?.en || ( typeof step === 'string' ? step : step.text ),
            description: stepTranslation.description?.[ language ] || stepTranslation.description?.en || step.description
        };
    } );

    return {
        ...service,
        name: translation.name?.[ language ] || translation.name?.en || service.name,
        description: translation.description?.[ language ] || translation.description?.en || service.description,
        steps: translatedSteps
    };
};
